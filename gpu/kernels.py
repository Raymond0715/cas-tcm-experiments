"""Direct register-accumulator input reuse, based on the identified Codex pattern.
Generated by generate_kernel.py. SHARE=True consumes each input vector in all
applicable output-row accumulators before advancing to the next source load.
SHARE=False retains the same accumulator layout, FMA arithmetic, and output tile.
"""
import triton
import triton.language as tl

@triton.jit
def direct_conv(X,W,Y,TI,TO,H:tl.constexpr,WI:tl.constexpr,CI:tl.constexpr,
                CO:tl.constexpr,K:tl.constexpr,S:tl.constexpr,P:tl.constexpr,
                OH:tl.constexpr,OW:tl.constexpr,DW:tl.constexpr,
                BX:tl.constexpr,BC:tl.constexpr,SHARE:tl.constexpr,TRACE:tl.constexpr):
    tile=tl.program_id(0)
    y0=tile//tl.cdiv(OW,BX)*4
    x0=tile%tl.cdiv(OW,BX)*BX
    oc=tl.program_id(1)*BC+tl.arange(0,BC)
    batch=tl.program_id(2)
    dx=tl.arange(0,BX);ox=x0+dx
    cta=(batch*tl.cdiv(CO,BC)+tl.program_id(1))*(tl.cdiv(OH,4)*tl.cdiv(OW,BX))+tile
    lanes=4*BC*BX
    acc0=tl.full((BC,BX),0,tl.float32)
    acc1=tl.full((BC,BX),0,tl.float32)
    acc2=tl.full((BC,BX),0,tl.float32)
    acc3=tl.full((BC,BX),0,tl.float32)
    if SHARE:
        for ic in range(1 if DW else CI):
            for sy in tl.static_range(3*S+K):
                iy=y0*S-P+sy
                for kx in tl.static_range(K):
                    ix=ox*S-P+kx
                    valid=(((sy>=0*S)&(sy<0*S+K)&(y0+0<OH))|((sy>=1*S)&(sy<1*S+K)&(y0+1<OH))|((sy>=2*S)&(sy<2*S+K)&(y0+2<OH))|((sy>=3*S)&(sy<3*S+K)&(y0+3<OH)))&(ox<OW)&(iy>=0)&(iy<H)&(ix>=0)&(ix<WI)
                    if DW:
                        v=tl.load(X+(batch*CI+oc[:,None])*H*WI+iy*WI+ix[None,:],
                                    (oc[:,None]<CI)&valid[None,:],0)
                    else:
                        av=tl.load(X+(batch*CI+ic)*H*WI+iy*WI+ix,valid,0)
                        v=av[None,:]
                    if sy >= 0*S and sy < 0*S+K:
                        if DW:
                            w=tl.load(W+oc*K*K+(sy-0*S)*K+kx,oc<CO,0)
                        else:
                            w=tl.load(W+(oc*CI+ic)*K*K+(sy-0*S)*K+kx,oc<CO,0)
                        acc0=tl.fma(v,w[:,None],acc0)
                    if TRACE:
                        slot=(0*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*(3*S+K)*K)+((ic*(3*S+K)+sy)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+0)*OW+ox[None,:]
                        mask=((sy>=0*S)&(sy<0*S+K)&(y0+0<OH))&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    if sy >= 1*S and sy < 1*S+K:
                        if DW:
                            w=tl.load(W+oc*K*K+(sy-1*S)*K+kx,oc<CO,0)
                        else:
                            w=tl.load(W+(oc*CI+ic)*K*K+(sy-1*S)*K+kx,oc<CO,0)
                        acc1=tl.fma(v,w[:,None],acc1)
                    if TRACE:
                        slot=(1*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*(3*S+K)*K)+((ic*(3*S+K)+sy)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+1)*OW+ox[None,:]
                        mask=((sy>=1*S)&(sy<1*S+K)&(y0+1<OH))&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    if sy >= 2*S and sy < 2*S+K:
                        if DW:
                            w=tl.load(W+oc*K*K+(sy-2*S)*K+kx,oc<CO,0)
                        else:
                            w=tl.load(W+(oc*CI+ic)*K*K+(sy-2*S)*K+kx,oc<CO,0)
                        acc2=tl.fma(v,w[:,None],acc2)
                    if TRACE:
                        slot=(2*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*(3*S+K)*K)+((ic*(3*S+K)+sy)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+2)*OW+ox[None,:]
                        mask=((sy>=2*S)&(sy<2*S+K)&(y0+2<OH))&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    if sy >= 3*S and sy < 3*S+K:
                        if DW:
                            w=tl.load(W+oc*K*K+(sy-3*S)*K+kx,oc<CO,0)
                        else:
                            w=tl.load(W+(oc*CI+ic)*K*K+(sy-3*S)*K+kx,oc<CO,0)
                        acc3=tl.fma(v,w[:,None],acc3)
                    if TRACE:
                        slot=(3*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*(3*S+K)*K)+((ic*(3*S+K)+sy)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+3)*OW+ox[None,:]
                        mask=((sy>=3*S)&(sy<3*S+K)&(y0+3<OH))&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
    else:
        for ic in range(1 if DW else CI):
            for ky in tl.static_range(K):
                for kx in tl.static_range(K):
                    ix=ox*S-P+kx
                    if DW:
                        w=tl.load(W+oc*K*K+(ky)*K+kx,oc<CO,0)
                    else:
                        w=tl.load(W+(oc*CI+ic)*K*K+(ky)*K+kx,oc<CO,0)
                    iy=(y0+0)*S-P+ky
                    valid=(y0+0<OH)&(ox<OW)&(iy>=0)&(iy<H)&(ix>=0)&(ix<WI)
                    if DW:
                        v=tl.load(X+(batch*CI+oc[:,None])*H*WI+iy*WI+ix[None,:],
                                    (oc[:,None]<CI)&valid[None,:],0)
                    else:
                        av=tl.load(X+(batch*CI+ic)*H*WI+iy*WI+ix,valid,0)
                        v=av[None,:]
                    acc0=tl.fma(v,w[:,None],acc0)
                    if TRACE:
                        slot=(0*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*K*K)+((ic*K+ky)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+0)*OW+ox[None,:]
                        mask=(y0+0<OH)&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    iy=(y0+1)*S-P+ky
                    valid=(y0+1<OH)&(ox<OW)&(iy>=0)&(iy<H)&(ix>=0)&(ix<WI)
                    if DW:
                        v=tl.load(X+(batch*CI+oc[:,None])*H*WI+iy*WI+ix[None,:],
                                    (oc[:,None]<CI)&valid[None,:],0)
                    else:
                        av=tl.load(X+(batch*CI+ic)*H*WI+iy*WI+ix,valid,0)
                        v=av[None,:]
                    acc1=tl.fma(v,w[:,None],acc1)
                    if TRACE:
                        slot=(1*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*K*K)+((ic*K+ky)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+1)*OW+ox[None,:]
                        mask=(y0+1<OH)&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    iy=(y0+2)*S-P+ky
                    valid=(y0+2<OH)&(ox<OW)&(iy>=0)&(iy<H)&(ix>=0)&(ix<WI)
                    if DW:
                        v=tl.load(X+(batch*CI+oc[:,None])*H*WI+iy*WI+ix[None,:],
                                    (oc[:,None]<CI)&valid[None,:],0)
                    else:
                        av=tl.load(X+(batch*CI+ic)*H*WI+iy*WI+ix,valid,0)
                        v=av[None,:]
                    acc2=tl.fma(v,w[:,None],acc2)
                    if TRACE:
                        slot=(2*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*K*K)+((ic*K+ky)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+2)*OW+ox[None,:]
                        mask=(y0+2<OH)&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
                    iy=(y0+3)*S-P+ky
                    valid=(y0+3<OH)&(ox<OW)&(iy>=0)&(iy<H)&(ix>=0)&(ix<WI)
                    if DW:
                        v=tl.load(X+(batch*CI+oc[:,None])*H*WI+iy*WI+ix[None,:],
                                    (oc[:,None]<CI)&valid[None,:],0)
                    else:
                        av=tl.load(X+(batch*CI+ic)*H*WI+iy*WI+ix,valid,0)
                        v=av[None,:]
                    acc3=tl.fma(v,w[:,None],acc3)
                    if TRACE:
                        slot=(3*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
                        offset=(cta*((1 if DW else CI)*K*K)+((ic*K+ky)*K+kx))*lanes+slot
                        addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+iy*WI+ix[None,:]
                        dst=(batch*CO+oc[:,None])*OH*OW+(y0+3)*OW+ox[None,:]
                        mask=(y0+3<OH)&(oc[:,None]<CO)&(ox[None,:]<OW)&(iy>=0)&(iy<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
                        tl.store(TI+offset,tl.where(mask,addr,-1))
                        tl.store(TO+offset,tl.where(mask,dst,-1))
    tl.store(Y+(batch*CO+oc[:,None])*OH*OW+(y0+0)*OW+ox[None,:],acc0,
             (oc[:,None]<CO)&(y0+0<OH)&(ox[None,:]<OW))
    tl.store(Y+(batch*CO+oc[:,None])*OH*OW+(y0+1)*OW+ox[None,:],acc1,
             (oc[:,None]<CO)&(y0+1<OH)&(ox[None,:]<OW))
    tl.store(Y+(batch*CO+oc[:,None])*OH*OW+(y0+2)*OW+ox[None,:],acc2,
             (oc[:,None]<CO)&(y0+2<OH)&(ox[None,:]<OW))
    tl.store(Y+(batch*CO+oc[:,None])*OH*OW+(y0+3)*OW+ox[None,:],acc3,
             (oc[:,None]<CO)&(y0+3<OH)&(ox[None,:]<OW))

def launch(x,w,y,c,v,q,trace_buffers=None):
    assert q['by']==4 and v in ('canonical','reuse')
    assert x.is_contiguous() and w.is_contiguous() and y.is_contiguous()
    n,ci,h,wi=x.shape;co,_,k,_=w.shape;oh,ow=y.shape[2:]
    assert c['groups'] in (1,ci) and (c['groups']==1 or co==ci)
    bx,bc=q['bx'],q['bc'];ti,to=trace_buffers if trace_buffers is not None else (x,x)
    grid=(triton.cdiv(oh,4)*triton.cdiv(ow,bx),triton.cdiv(co,bc),n)
    return direct_conv[grid](x,w,y,ti,to,h,wi,ci,co,k,c['stride'],c['padding'],oh,ow,c['groups']!=1,
                             bx,bc,v=='reuse',trace_buffers is not None,num_warps=4)
