"""Generate explicit four-row accumulators; no intermediate product/gather tensor."""
from pathlib import Path
ROOT=Path(__file__).resolve().parent
head='''"""Direct register-accumulator input reuse, based on the identified Codex pattern.
Generated by generate_kernel.py. SHARE=True consumes each input vector in all
applicable output-row accumulators before advancing to the next source load.
SHARE=False retains the same accumulator layout, FMA arithmetic, and output tile.
"""
import triton
import triton.language as tl

@triton.jit
def direct_conv(X,W,Y,TI,TO,H:tl.constexpr,WI:tl.constexpr,CI:tl.constexpr,
                CO:tl.constexpr,K:tl.constexpr,S:tl.constexpr,P:tl.constexpr,
                OH:tl.constexpr,OW:tl.constexpr,DW:tl.constexpr,
                BX:tl.constexpr,BC:tl.constexpr,SHARE:tl.constexpr,TRACE:tl.constexpr):
    tile=tl.program_id(0)
    y0=tile//tl.cdiv(OW,BX)*4
    x0=tile%tl.cdiv(OW,BX)*BX
    oc=tl.program_id(1)*BC+tl.arange(0,BC)
    batch=tl.program_id(2)
    dx=tl.arange(0,BX);ox=x0+dx
    cta=(batch*tl.cdiv(CO,BC)+tl.program_id(1))*(tl.cdiv(OH,4)*tl.cdiv(OW,BX))+tile
    lanes=4*BC*BX
'''
code=head+''.join(f'    acc{r}=tl.full((BC,BX),0,tl.float32)\n' for r in range(4))
def load(indent,iy,var,rowvalid):
 return f'''{indent}valid=({rowvalid})&(ox<OW)&({iy}>=0)&({iy}<H)&(ix>=0)&(ix<WI)
{indent}if DW:
{indent}    {var}=tl.load(X+(batch*CI+oc[:,None])*H*WI+{iy}*WI+ix[None,:],
{indent}                (oc[:,None]<CI)&valid[None,:],0)
{indent}else:
{indent}    av=tl.load(X+(batch*CI+ic)*H*WI+{iy}*WI+ix,valid,0)
{indent}    {var}=av[None,:]
'''
def weight(indent,ky):
 return f'''{indent}if DW:
{indent}    w=tl.load(W+oc*K*K+({ky})*K+kx,oc<CO,0)
{indent}else:
{indent}    w=tl.load(W+(oc*CI+ic)*K*K+({ky})*K+kx,oc<CO,0)
'''
def capture(indent,r,step,steps,iy,rowvalid):
 return f'''{indent}if TRACE:
{indent}    slot=({r}*BC+tl.arange(0,BC)[:,None])*BX+dx[None,:]
{indent}    offset=(cta*({steps})+({step}))*lanes+slot
{indent}    addr=(batch*CI+(oc[:,None] if DW else ic))*H*WI+{iy}*WI+ix[None,:]
{indent}    dst=(batch*CO+oc[:,None])*OH*OW+(y0+{r})*OW+ox[None,:]
{indent}    mask=({rowvalid})&(oc[:,None]<CO)&(ox[None,:]<OW)&({iy}>=0)&({iy}<H)&(ix[None,:]>=0)&(ix[None,:]<WI)
{indent}    tl.store(TI+offset,tl.where(mask,addr,-1))
{indent}    tl.store(TO+offset,tl.where(mask,dst,-1))
'''
code+='''    if SHARE:
        for ic in range(1 if DW else CI):
            for sy in tl.static_range(3*S+K):
                iy=y0*S-P+sy
                for kx in tl.static_range(K):
                    ix=ox*S-P+kx
'''
rv='|'.join(f'((sy>={r}*S)&(sy<{r}*S+K)&(y0+{r}<OH))' for r in range(4))
code+=load('                    ','iy','v',rv)
for r in range(4):
 code+=f'                    if sy >= {r}*S and sy < {r}*S+K:\n'
 code+=weight('                        ',f'sy-{r}*S')
 code+=f'                        acc{r}=tl.fma(v,w[:,None],acc{r})\n'
 # All trace lanes written, including inactive rows, avoiding hidden initialization.
 code+=capture('                    ',r,'(ic*(3*S+K)+sy)*K+kx','(1 if DW else CI)*(3*S+K)*K','iy',f'(sy>={r}*S)&(sy<{r}*S+K)&(y0+{r}<OH)')
code+='''    else:
        for ic in range(1 if DW else CI):
            for ky in tl.static_range(K):
                for kx in tl.static_range(K):
                    ix=ox*S-P+kx
'''
code+=weight('                    ','ky')
for r in range(4):
 code+=f'                    iy=(y0+{r})*S-P+ky\n'
 code+=load('                    ','iy','v',f'y0+{r}<OH')
 code+=f'                    acc{r}=tl.fma(v,w[:,None],acc{r})\n'
 code+=capture('                    ',r,'(ic*K+ky)*K+kx','(1 if DW else CI)*K*K','iy',f'y0+{r}<OH')
for r in range(4):
 code+=f'''    tl.store(Y+(batch*CO+oc[:,None])*OH*OW+(y0+{r})*OW+ox[None,:],acc{r},
             (oc[:,None]<CO)&(y0+{r}<OH)&(ox[None,:]<OW))
'''
code+='''
def launch(x,w,y,c,v,q,trace_buffers=None):
    assert q['by']==4 and v in ('canonical','reuse')
    assert x.is_contiguous() and w.is_contiguous() and y.is_contiguous()
    n,ci,h,wi=x.shape;co,_,k,_=w.shape;oh,ow=y.shape[2:]
    assert c['groups'] in (1,ci) and (c['groups']==1 or co==ci)
    bx,bc=q['bx'],q['bc'];ti,to=trace_buffers if trace_buffers is not None else (x,x)
    grid=(triton.cdiv(oh,4)*triton.cdiv(ow,bx),triton.cdiv(co,bc),n)
    return direct_conv[grid](x,w,y,ti,to,h,wi,ci,co,k,c['stride'],c['padding'],oh,ow,c['groups']!=1,
                             bx,bc,v=='reuse',trace_buffers is not None,num_warps=4)
'''
(ROOT/'kernels.py').write_text(code)
